let currentLang = "en";

function t(key) {
  const val = STR[currentLang][key];
  if (val !== undefined) return val;
  return STR["en"][key] || key;
}

function setLang(lang) {
  currentLang = lang;
  document.documentElement.lang = lang === "zh-Hant" ? "zh-Hant" : "en";
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const val = t(el.dataset.i18n);
    el.textContent = val;
    el.style.visibility = val === "" ? "hidden" : "";
  });
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });
  if (window.AM22 && window.AM22.renderCart)    window.AM22.renderCart();
  if (window.AM22 && window.AM22.renderContact) window.AM22.renderContact();
}
